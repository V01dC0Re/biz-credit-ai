func (h *Handler) Dashboard(c *gin.Context) {
	user, ok := c.MustGet(middleware.UserContextKey).(models.User)
	if !ok {
		fail(c, http.StatusUnauthorized, "Пользователь не найден")
		return
	}
	if user.Role != models.RoleClient {
		fail(c, http.StatusForbidden, "Дашборд доступен только клиентам")
		return
	}
	if user.INN == nil {
		fail(c, http.StatusNotFound, "Компания не найдена")
		return
	}
	var company models.Company
	err := h.DB.WithContext(c.Request.Context()).Where("inn = ?", *user.INN).First(&company).Error
	if errors.Is(err, gorm.ErrRecordNotFound) {
		fail(c, http.StatusNotFound, "Компания не найдена")
		return
	}
	if err != nil {
		fail(c, http.StatusInternalServerError, "Не удалось получить компанию")
		return
	}
	var application models.Application
	var active *models.Application
	err = h.DB.WithContext(c.Request.Context()).Where("user_id = ? AND company_id = ? AND status NOT IN ?", user.ID, company.ID,
		[]models.ApplicationStatus{models.StatusRejected, models.StatusIssued, models.StatusCancelled}).Order("id DESC").First(&application).Error
	if err == nil {
		active = &application
	} else if !errors.Is(err, gorm.ErrRecordNotFound) {
		fail(c, http.StatusInternalServerError, "Не удалось получить заявку")
		return
	}

	// Определение ключевого сегмента текущей компании
	primaryTarget := "all"
	if company.AgeMonths > 0 && company.AgeMonths < 6 {
		primaryTarget = "startup"
	} else if strings.HasPrefix(company.OKVED, "62") || strings.HasPrefix(company.OKVED, "63") {
		primaryTarget = "it"
	} else if strings.HasPrefix(company.OKVED, "47") {
		primaryTarget = "retail"
	} else if strings.HasPrefix(company.OKVED, "25") || strings.HasPrefix(company.OKVED, "10") {
		primaryTarget = "production"
	}

	// Формирование персонализированного списка userNews:
	// 1. Новости целевого сегмента
	// 2. Новости для всех ("all")
	// 3. Остальные новости каталога
	seen := make(map[int]bool)
	userNews := make([]NewsItem, 0, len(allNewsCatalog))

	for _, item := range allNewsCatalog {
		if item.TargetAudience == primaryTarget {
			item.Content = item.Summary
			userNews = append(userNews, item)
			seen[item.ID] = true
		}
	}
	for _, item := range allNewsCatalog {
		if item.TargetAudience == "all" && !seen[item.ID] {
			item.Content = item.Summary
			userNews = append(userNews, item)
			seen[item.ID] = true
		}
	}
	for _, item := range allNewsCatalog {
		if !seen[item.ID] {
			item.Content = item.Summary
			userNews = append(userNews, item)
			seen[item.ID] = true
		}
	}

	c.JSON(http.StatusOK, gin.H{
		"active_application": active,
		"news_feed":          userNews,
		"company_info":       company,
		"primary_target":     primaryTarget,
	})
}
